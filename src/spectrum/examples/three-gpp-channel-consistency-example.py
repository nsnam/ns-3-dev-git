def angular_difference_deg(series):
    """Return per-sample angular changes without wraparound discontinuities."""
    values = series.to_numpy()
    unwrapped = np.unwrap(np.radians(values))
    differences = np.diff(unwrapped, prepend=unwrapped[0])
    return pd.Series(np.degrees(differences), index=series.index)


def padded_limits(series_list, padding=0.1, minimum_span=1.0):
    """Return common plot limits for one or more numeric series."""
    values = np.concatenate([np.asarray(series) for series in series_list])
    value_min = float(np.nanmin(values))
    value_max = float(np.nanmax(values))
    span = max(value_max - value_min, minimum_span)
    margin = padding * span
    return value_min - margin, value_max + margin


def symmetric_limits(series_list, padding=0.2, minimum=1.0):
    """Return symmetric limits around zero for one or more numeric series."""
    values = np.concatenate([np.asarray(series) for series in series_list])
    maximum = max(float(np.nanmax(np.abs(values))), minimum)
    return -(1.0 + padding) * maximum, (1.0 + padding) * maximum


def get_transition_times(time, state):
    """Return NLOS-to-LOS and LOS-to-NLOS transition times."""
    previous_state = state.shift(1, fill_value=state.iloc[0])
    nlos_to_los = []
    los_to_nlos = []

    for timestamp, previous, current in zip(time, previous_state, state):
        if previous == current:
            continue
        if previous.startswith("NLOS") and current == "LOS":
            nlos_to_los.append(timestamp)
        elif previous == "LOS" and current.startswith("NLOS"):
            los_to_nlos.append(timestamp)

    return nlos_to_los, los_to_nlos


def add_state_vlines(axis, nlos_to_los, los_to_nlos):
    """Draw channel-state transitions on an axis."""
    for timestamp in nlos_to_los:
        axis.axvline(timestamp, color="green", linestyle="-", linewidth=0.9, alpha=0.6)
    for timestamp in los_to_nlos:
        axis.axvline(timestamp, color="red", linestyle="--", linewidth=0.9, alpha=0.6)


def add_state_legend(axis, nlos_to_los, los_to_nlos, location="best"):
    """Add a legend for channel-state transitions that occur in the trace."""
    handles = []
    if nlos_to_los:
        handles.append(Line2D([0], [0], color="green", linestyle="-", label="NLOS to LOS"))
    if los_to_nlos:
        handles.append(Line2D([0], [0], color="red", linestyle="--", label="LOS to NLOS"))
    if handles:
        axis.legend(handles=handles, loc=location)


def scenario_limits(buildings, tx_x, tx_y, rx_x, rx_y):
    """Return bounds containing the buildings and complete node trajectories."""
    x_values = np.concatenate(
        [buildings[0].to_numpy(), buildings[2].to_numpy(), tx_x.to_numpy(), rx_x.to_numpy()]
    )
    y_values = np.concatenate(
        [buildings[1].to_numpy(), buildings[3].to_numpy(), tx_y.to_numpy(), rx_y.to_numpy()]
    )
    x_min, x_max = float(x_values.min()), float(x_values.max())
    y_min, y_max = float(y_values.min()), float(y_values.max())
    margin = max(0.05 * max(x_max - x_min, y_max - y_min), 5.0)
    return (x_min - margin, x_max + margin), (y_min - margin, y_max + margin)


def add_buildings(axis, buildings):
    """Draw all scenario buildings on an axis."""
    for _, building in buildings.iterrows():
        x_min, y_min, x_max, y_max = building
        rectangle = patches.Rectangle(
            (x_min, y_min),
            x_max - x_min,
            y_max - y_min,
            facecolor="gray",
            edgecolor="black",
            alpha=0.5,
            linewidth=0.8,
        )
        axis.add_patch(rectangle)


def coordinate_label(name, x, y):
    return f"{name} ({x:.2f}, {y:.2f}) m"


def plot_scenario(output_filename, buildings, tx_x, tx_y, rx_x, rx_y, x_limits, y_limits):
    """Generate a static figure of the buildings and RX trajectory."""
    figure, axis = plt.subplots(figsize=(8, 8))
    add_buildings(axis, buildings)

    axis.plot(
        rx_x,
        rx_y,
        color="tab:orange",
        linewidth=2.0,
        label="RX trajectory",
        zorder=3,
    )
    axis.scatter(
        tx_x.iloc[0],
        tx_y.iloc[0],
        marker="^",
        color="blue",
        s=110,
        label=coordinate_label("TX", tx_x.iloc[0], tx_y.iloc[0]),
        zorder=4,
    )
    axis.scatter(
        rx_x.iloc[0],
        rx_y.iloc[0],
        marker="o",
        color="green",
        s=80,
        label=coordinate_label("RX start", rx_x.iloc[0], rx_y.iloc[0]),
        zorder=4,
    )
    axis.scatter(
        rx_x.iloc[-1],
        rx_y.iloc[-1],
        marker="x",
        color="red",
        s=110,
        linewidth=2.5,
        label=coordinate_label("RX end", rx_x.iloc[-1], rx_y.iloc[-1]),
        zorder=4,
    )

    axis.set_xlabel("X [m]", fontsize=18)
    axis.set_ylabel("Y [m]", fontsize=18)
    axis.set_title("Simulation scenario", fontsize=20)
    axis.set_aspect("equal")
    axis.set_xlim(*x_limits)
    axis.set_ylim(*y_limits)
    axis.grid(True, linewidth=0.4, alpha=0.5)
    axis.legend(loc="best", fontsize=18)
    axis.tick_params(axis="both", labelsize=18)
    figure.tight_layout()
    figure.savefig(output_filename, dpi=300, bbox_inches="tight")
    plt.close(figure)


def plot_snr(output_filename, time, snr, snr_diff, nlos_to_los, los_to_nlos):
    """Generate the static SNR and SNR-change figure."""
    figure, axes = plt.subplots(2, 1, figsize=(10, 6), sharex=True)

    axes[0].plot(time, snr, "k-", linewidth=1.2)
    axes[0].set_ylabel("SNR [dB]")
    axes[0].set_ylim(*SNR_Y_LIMITS)
    axes[0].grid(True)
    add_state_vlines(axes[0], nlos_to_los, los_to_nlos)
    add_state_legend(axes[0], nlos_to_los, los_to_nlos)

    axes[1].plot(time, snr_diff, "k-", linewidth=1.2)
    axes[1].set_ylabel(r"$\Delta$ SNR [dB]")
    axes[1].set_xlabel("Time [s]")
    axes[1].set_ylim(*SNR_DIFF_Y_LIMITS)
    axes[1].grid(True)
    add_state_vlines(axes[1], nlos_to_los, los_to_nlos)

    axes[0].set_xlim(time.min(), time.max())
    figure.tight_layout()
    figure.savefig(output_filename, dpi=300, bbox_inches="tight")
    plt.close(figure)


def plot_components(axis, time, components, nlos_to_los, los_to_nlos):
    """Plot C1-C3 on one axis."""
    for index, (label, style, color, component) in enumerate(
        zip(COMPONENT_LABELS, COMPONENT_STYLES, COMPONENT_COLORS, components)
    ):
        axis.plot(
            time,
            component,
            linestyle=style,
            color=color,
            linewidth=1.3,
            label=label,
            zorder=len(COMPONENT_LABELS) - index,
        )
    add_state_vlines(axis, nlos_to_los, los_to_nlos)
    axis.set_xlim(time.min(), time.max())
    axis.grid(True)
    axis.legend(loc="best")


def plot_cluster_overview(
    output_filename,
    time,
    component_powers,
    delays_us,
    component_power_differences,
    delay_differences_us,
    nlos_to_los,
    los_to_nlos,
):
    """Generate an overview of channel component powers and delays for C1-C3."""
    figure, axes = plt.subplots(2, 2, figsize=(14, 8), sharex=True)
    plots = [
        (axes[0, 0], component_powers, "Channel component power [dB]"),
        (axes[0, 1], delays_us, r"Cluster delay [$\mu$s]"),
        (axes[1, 0], component_power_differences, "Changes in channel component power [dB]"),
        (axes[1, 1], delay_differences_us, r"$\Delta$ delay [$\mu$s]"),
    ]

    for axis, components, ylabel in plots:
        plot_components(axis, time, components, nlos_to_los, los_to_nlos)
        axis.set_ylabel(ylabel)
        axis.set_xlabel("Time [s]")

    axes[0, 0].set_ylim(*padded_limits(component_powers, minimum_span=1.0))
    axes[0, 1].set_ylim(*padded_limits(delays_us, minimum_span=0.1))
    axes[1, 0].set_ylim(*symmetric_limits(component_power_differences, minimum=0.1))
    axes[1, 1].set_ylim(*symmetric_limits(delay_differences_us, minimum=0.01))

    figure.tight_layout()
    figure.savefig(output_filename, dpi=300, bbox_inches="tight")
    plt.close(figure)


