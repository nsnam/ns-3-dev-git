def plot_metric_grid(
    output_filename,
    time,
    values,
    differences,
    value_label,
    difference_label,
    nlos_to_los,
    los_to_nlos,
    minimum_value_span,
    minimum_difference,
):
    """Generate a 2x3 figure with each component and its per-sample change."""
    figure, axes = plt.subplots(2, 3, figsize=(16, 6), sharex="col")
    value_limits = padded_limits(values, minimum_span=minimum_value_span)
    difference_limits = symmetric_limits(differences, minimum=minimum_difference)

    for index, (label, value, difference) in enumerate(zip(COMPONENT_LABELS, values, differences)):
        axes[0, index].plot(time, value, color="black", linewidth=1.0)
        axes[0, index].set_title(label)
        axes[0, index].set_ylabel(value_label)
        axes[0, index].set_ylim(*value_limits)
        axes[0, index].grid(True)
        add_state_vlines(axes[0, index], nlos_to_los, los_to_nlos)

        axes[1, index].plot(time, difference, color="black", linewidth=1.0)
        axes[1, index].set_ylabel(difference_label)
        axes[1, index].set_xlabel("Time [s]")
        axes[1, index].set_ylim(*difference_limits)
        axes[1, index].grid(True)
        add_state_vlines(axes[1, index], nlos_to_los, los_to_nlos)

        axes[0, index].set_xlim(time.min(), time.max())

    figure.tight_layout()
    figure.savefig(output_filename, dpi=300, bbox_inches="tight")
    plt.close(figure)


def plot_animation(
    output_filename,
    buildings,
    time,
    tx_x,
    tx_y,
    rx_x,
    rx_y,
    snr,
    snr_diff,
    nlos_to_los,
    los_to_nlos,
    x_limits,
    y_limits,
):
    """Generate the map and SNR animation."""
    figure, axes = plt.subplots(2, 2, figsize=(24, 9), dpi=150)
    map_axis, snr_axis = axes[0]
    zoom_axis, diff_axis = axes[1]

    add_buildings(map_axis, buildings)
    map_axis.set_xlabel("X [m]")
    map_axis.set_ylabel("Y [m]")
    map_axis.set_aspect("equal")
    map_axis.set_xlim(*x_limits)
    map_axis.set_ylim(*y_limits)
    tx_marker = map_axis.scatter([], [], marker="^", color="blue", s=80)
    rx_marker = map_axis.scatter([], [], marker="o", color="red", s=60)

    snr_axis.set_xlabel("Time [s]")
    snr_axis.set_ylabel("SNR [dB]")
    snr_axis.set_xlim(time.min(), time.max())
    snr_axis.set_ylim(*SNR_Y_LIMITS)
    snr_axis.grid(True)
    (snr_line,) = snr_axis.plot([], [], "k-", linewidth=1.5)
    add_state_vlines(snr_axis, nlos_to_los, los_to_nlos)
    add_state_legend(snr_axis, nlos_to_los, los_to_nlos)

    zoom_axis.set_xlabel("Time [s]")
    zoom_axis.set_ylabel("SNR [dB] (zoom)")
    zoom_axis.set_ylim(*SNR_Y_LIMITS)
    zoom_axis.grid(True)
    (zoom_line,) = zoom_axis.plot([], [], "k-", linewidth=1.5)
    add_state_vlines(zoom_axis, nlos_to_los, los_to_nlos)

    diff_axis.set_xlabel("Time [s]")
    diff_axis.set_ylabel(r"$\Delta$ SNR [dB]")
    diff_axis.set_xlim(time.min(), time.max())
    diff_axis.set_ylim(*SNR_DIFF_Y_LIMITS)
    diff_axis.grid(True)
    (diff_line,) = diff_axis.plot([], [], "k-", linewidth=1.5)
    add_state_vlines(diff_axis, nlos_to_los, los_to_nlos)

    maximum_frames = 800
    frame_step = max(1, len(time) // maximum_frames)
    frame_indices = list(range(0, len(time), frame_step))
    if frame_indices[-1] != len(time) - 1:
        frame_indices.append(len(time) - 1)

    def update(frame_index):
        timestamp = time.iloc[frame_index]
        tx_marker.set_offsets([[tx_x.iloc[frame_index], tx_y.iloc[frame_index]]])
        rx_marker.set_offsets([[rx_x.iloc[frame_index], rx_y.iloc[frame_index]]])
        map_axis.set_title(f"Time = {timestamp:.3f} s")

        snr_line.set_data(time.iloc[: frame_index + 1], snr.iloc[: frame_index + 1])
        start_time = max(time.min(), timestamp - ZOOM_WINDOW_S / 2.0)
        end_time = min(time.max(), timestamp + ZOOM_WINDOW_S / 2.0)
        mask = (time >= start_time) & (time <= end_time)
        zoom_axis.set_xlim(start_time, end_time)
        zoom_line.set_data(time[mask], snr[mask])
        diff_line.set_data(time.iloc[: frame_index + 1], snr_diff.iloc[: frame_index + 1])
        return tx_marker, rx_marker, snr_line, zoom_line, diff_line

    generated_animation = animation.FuncAnimation(
        figure,
        update,
        frames=frame_indices,
        interval=0,
        blit=False,
    )
    generated_animation.save(output_filename, writer="pillow", fps=25, dpi=90)
    plt.close(figure)


def plot_component_power_animation(
    output_filename,
    time,
    component_powers,
    component_power_differences,
    nlos_to_los,
    los_to_nlos,
):
    """Generate an animation of C1-C3 channel-component powers and their changes."""
    figure, axes = plt.subplots(2, 1, figsize=(12, 8), dpi=120, sharex=True)

    power_axis = axes[0]
    difference_axis = axes[1]

    power_axis.set_ylabel("Channel component power [dB]")
    power_axis.grid(True)
    power_axis.set_xlim(time.min(), time.max())
    power_axis.set_ylim(*padded_limits(component_powers, minimum_span=1.0))
    add_state_vlines(power_axis, nlos_to_los, los_to_nlos)

    difference_axis.set_xlabel("Time [s]")
    difference_axis.set_ylabel(r"$\Delta$ channel component power [dB]")
    difference_axis.grid(True)
    difference_axis.set_xlim(time.min(), time.max())
    difference_axis.set_ylim(*symmetric_limits(component_power_differences, minimum=0.1))
    add_state_vlines(difference_axis, nlos_to_los, los_to_nlos)

    power_lines = []
    difference_lines = []

    for index, (label, style, color) in enumerate(
        zip(COMPONENT_LABELS, COMPONENT_STYLES, COMPONENT_COLORS)
    ):
        (power_line,) = power_axis.plot(
            [],
            [],
            linestyle=style,
            color=color,
            linewidth=1.5,
            label=label,
            zorder=len(COMPONENT_LABELS) - index,
        )
        power_lines.append(power_line)

        (difference_line,) = difference_axis.plot(
            [],
            [],
            linestyle=style,
            color=color,
            linewidth=1.5,
            label=label,
            zorder=len(COMPONENT_LABELS) - index,
        )
        difference_lines.append(difference_line)

    power_axis.legend(loc="best")
    difference_axis.legend(loc="best")

    maximum_frames = 800
    frame_step = max(1, len(time) // maximum_frames)
    frame_indices = list(range(0, len(time), frame_step))

    if frame_indices[-1] != len(time) - 1:
        frame_indices.append(len(time) - 1)

    def update(frame_index):
        for index in range(3):
            power_lines[index].set_data(
                time.iloc[: frame_index + 1],
                component_powers[index].iloc[: frame_index + 1],
            )

            difference_lines[index].set_data(
                time.iloc[: frame_index + 1],
                component_power_differences[index].iloc[: frame_index + 1],
            )

        return (*power_lines, *difference_lines)

    generated_animation = animation.FuncAnimation(
        figure,
        update,
        frames=frame_indices,
        interval=0,
        blit=False,
    )

    generated_animation.save(
        output_filename,
        writer="pillow",
        fps=25,
        dpi=120,
    )

    plt.close(figure)


def main():
    options = parse_arguments()
    data = pd.read_csv(TRACE_FILE, sep=r"\s+", comment="#")
    buildings = pd.read_csv(BUILDINGS_FILE, sep=r"\s+", comment="#", header=None)

    required_columns = {
        TIME_COL,
        TX_X_COL,
        TX_Y_COL,
        RX_X_COL,
        RX_Y_COL,
        STATE_COL,
        SNR_COL,
        *CLUSTER_POWER_COLS,
        *COMPONENT_POWER_COLS,
        *DELAY_COLS,
        *AOA_COLS,
        *ZOA_COLS,
    }

    missing_columns = required_columns.difference(data.columns)
    if missing_columns:
        missing = ", ".join(sorted(missing_columns))
        raise ValueError(f"Trace is missing required columns: {missing}")

    time = data[TIME_COL]
    tx_x = data[TX_X_COL]
    tx_y = data[TX_Y_COL]
    rx_x = data[RX_X_COL]
    rx_y = data[RX_Y_COL]
    state = data[STATE_COL].astype(str)
    snr = data[SNR_COL]
    snr_diff = snr.diff().fillna(0.0)

    cluster_powers = [data[column] for column in CLUSTER_POWER_COLS]
    component_powers = [data[column] for column in COMPONENT_POWER_COLS]
    delays_us = [data[column] * 1e6 for column in DELAY_COLS]
    aoas = [data[column] for column in AOA_COLS]
    zoas = [data[column] for column in ZOA_COLS]

    cluster_power_differences = [cluster.diff().fillna(0.0) for cluster in cluster_powers]
    component_power_differences = [component.diff().fillna(0.0) for component in component_powers]
    delay_differences_us = [component.diff().fillna(0.0) for component in delays_us]
    aoa_differences = [angular_difference_deg(component) for component in aoas]
    zoa_differences = [angular_difference_deg(component) for component in zoas]

    nlos_to_los, los_to_nlos = get_transition_times(time, state)
    x_limits, y_limits = scenario_limits(buildings, tx_x, tx_y, rx_x, rx_y)

